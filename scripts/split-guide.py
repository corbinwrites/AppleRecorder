def parse(lines):
    """{id: (start, end)} from fence-aware '## N.' and '### N.M' headings. 0-based, end exclusive.
    A top-level '# ' heading (outside code fences) also ends a section."""
    heads, in_fence = [], False
    for i, ln in enumerate(lines):
        if ln.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m2 = re.match(r"^## (\d+)\. ", ln)
        m3 = re.match(r"^### (\d+\.\d+) ", ln)
        if m2:
            heads.append((i, 2, m2.group(1)))
        elif m3:
            heads.append((i, 3, m3.group(1)))
        elif re.match(r"^# ", ln):
            heads.append((i, 1, None))
    spans = {}
    for k, (i, lvl, hid) in enumerate(heads):
        if hid is None:
            continue
        end = len(lines)
        for (j, lvl2, _) in heads[k + 1:]:
            if lvl2 == 1 or (lvl == 2 and lvl2 <= 2) or (lvl == 3 and lvl2 <= 3):
                end = j
                break
        spans[hid] = (i, end)
    return spans


def exit_checks(lines):
    out = {}
    for ln in lines:
        m = re.match(r"^\| \*\*(P[0-9.]+)\*\* \| (.*) \| (.*) \|$", ln)
        if m:
            out[m.group(1)] = (m.group(2).strip(), m.group(3).strip())
    return out


def main():
    lines = GUIDE.read_text(encoding="utf-8").split("\n")
    spans, table = parse(lines), exit_checks(lines)
    OUT.mkdir(parents=True, exist_ok=True)
    SRC.mkdir(exist_ok=True)
    index = ["# Task files", "",
             "Generated from `docs/BUILD-GUIDE.md` by `scripts/split-guide.py` (`make tasks`). Do not edit. One session = one file.",
             "", "| Step | Verify | Notes |", "|---|---|---|"]
    for step, (secs, verify, note) in STEPS.items():
        if step not in table:
            sys.exit(f"step {step} missing from the guide's section 32 table")
        deliver, exit_check = table[step]
        parts = ["<!-- GENERATED by scripts/split-guide.py from docs/BUILD-GUIDE.md. Do not edit; run `make tasks`. -->",
                 f"# Task {step}", "",
                 f"**Deliverable:** {deliver}", "",
                 f"**Exit check:** {exit_check}", "",
                 f"VERIFY: {verify}", ""]
        if note:
            parts += [f"**Note:** {note}", ""]
        parts += ["**Before you start:** read `AGENTS.md`. The spec sections you need are below; you do not need the rest of the guide.",
                  f"**When done:** run the VERIFY command, update `PROGRESS.md`, commit `{step}: <what>`, stop.", ""]
        body = SRC / f"{step}.body.md"
        if body.exists():
            parts += ["---", "", body.read_text(encoding="utf-8").rstrip(), ""]
        for s in secs:
            if s not in spans:
                sys.exit(f"section {s} not found in the guide (needed by {step})")
            a, b = spans[s]
            parts += ["---", f"<!-- source: BUILD-GUIDE.md section {s}, lines {a + 1}-{b} -->", ""] + lines[a:b]
        (OUT / f"{step}.md").write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")
        index.append(f"| {step} | `{verify}` | {note} |")
        print(f"{step}: {len(secs)} sections")
    (OUT / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
